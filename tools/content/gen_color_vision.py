#!/usr/bin/env python3
"""Generates the colour-blind UI palettes: data/config/color_vision.json (X-12).

For each deficiency (protanopia, deuteranopia, tritanopia) and each group of UI colours that must stay apart (item
rarity tiers; chat and caption colours; tooltip bonus/penalty lines), a seeded search moves the colours in CIELAB
(lightness within +-10 and never below 55, so the outlined text stays readable) to push apart the closest pairs as the
viewer sees them (Machado, Oliveira and Fernandes 2009 simulation, the matrices in
src/Strata.Core/Presentation/ColorVision.cs), while staying close to Terraria's colours. Only colours that moved are
written as remaps. Strata.Tools validate re-checks the shipped file (ColorVisionPalette.Validate): every group's
closest simulated pair must be at least minDistance apart.

Usage: python3 tools/content/gen_color_vision.py [--check]
"""
import json
import pathlib
import sys

import numpy as np

REPO = pathlib.Path(__file__).resolve().parents[2]
OUT = REPO / "data" / "config" / "color_vision.json"
SEED = 3
STEPS = 4000
MIN_DISTANCE = 12

SIM = {
    "protanopia": [[0.152286, 1.052583, -0.204868], [0.114503, 0.786281, 0.099216], [-0.003882, -0.048116, 1.051998]],
    "deuteranopia": [[0.367322, 0.860646, -0.227968], [0.280085, 0.672501, 0.047413], [-0.011820, 0.042940, 0.968881]],
    "tritanopia": [[1.255528, -0.076749, -0.178779], [-0.078411, 0.930809, 0.147602], [0.004733, 0.691367, 0.303900]],
}

# Colours that must stay distinguishable from each other, and the ones never changed (white text, grey, muted info).
GROUPS = {
    "rarity": ["#828282", "#ffffff", "#9696ff", "#96ff96", "#ffc896", "#ff9696", "#ff96ff", "#d2a0ff", "#96ff0a",
               "#ffff0a", "#05c8ff", "#ff2864", "#b428ff", "#ffaf00"],
    "chat": ["#ffffff", "#af4bff", "#327dff", "#ff1919", "#32ff82", "#fff014", "#96d2ff", "#ffaa78"],
    "tooltip": ["#78be78", "#be7878", "#bec4dc", "#ffffff"],
}
FIXED = {"#ffffff", "#828282", "#bec4dc"}

XYZ = np.array([[0.4124, 0.3576, 0.1805], [0.2126, 0.7152, 0.0722], [0.0193, 0.1192, 0.9505]])
WHITE = np.array([0.95047, 1.0, 1.08883])


def rgb(hex_: str) -> np.ndarray:
    return np.array([int(hex_[i:i + 2], 16) for i in (1, 3, 5)], dtype=float) / 255.0


def hexof(c) -> str:
    return "#%02x%02x%02x" % tuple(int(round(v * 255)) for v in c)


def linear(c):
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def encode(c):
    c = np.clip(c, 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * c ** (1 / 2.4) - 0.055)


def lab(c):
    f = XYZ @ linear(c) / WHITE
    f = np.where(f > 0.008856, np.cbrt(f), 7.787 * f + 16 / 116)
    return np.array([116 * f[1] - 16, 500 * (f[0] - f[1]), 200 * (f[1] - f[2])])


def from_lab(v):
    fy = (v[0] + 16) / 116
    f = np.array([fy + v[1] / 500, fy, fy - v[2] / 200])
    lin = np.linalg.inv(XYZ) @ (np.where(f ** 3 > 0.008856, f ** 3, (f - 16 / 116) / 7.787) * WHITE)
    if np.any(lin < -0.002) or np.any(lin > 1.002):
        return None  # outside the sRGB gamut
    return np.round(encode(np.clip(lin, 0, 1)) * 255) / 255


def seen(c, sim):
    return lab(encode(np.array(sim) @ linear(c)))


def distances(cols, sim):
    p = [seen(c, sim) for c in cols]
    return np.array([np.linalg.norm(p[i] - p[j]) for i in range(len(p)) for j in range(i + 1, len(p))])


def score(cols, orig, sim):
    d = distances(cols, sim)
    soft_min = -8 * np.log(np.sum(np.exp(-d / 8)))
    shift = np.mean([np.linalg.norm(lab(c) - lab(o)) for c, o in zip(cols, orig)])
    return soft_min - 0.25 * shift


def tune(hexes, sim, rng):
    orig = [rgb(h) for h in hexes]
    cols = list(orig)
    best = score(cols, orig, sim)
    for _ in range(STEPS):
        k = int(rng.integers(len(cols)))
        if hexes[k] in FIXED:
            continue
        base, now = lab(orig[k]), lab(cols[k])
        cand = now + np.array([rng.normal(0, 3), rng.normal(0, 12), rng.normal(0, 12)])
        cand[0] = np.clip(cand[0], max(55, base[0] - 10), min(100, base[0] + 10))
        c = from_lab(cand)
        if c is None:
            continue
        trial = cols[:k] + [c] + cols[k + 1:]
        s = score(trial, orig, sim)
        if s > best:
            best, cols = s, trial
    return {h: hexof(c) for h, o, c in zip(hexes, orig, cols) if np.linalg.norm(lab(c) - lab(o)) > 4}


def build():
    rng = np.random.default_rng(SEED)
    modes = {}
    for mode, sim in SIM.items():
        remap = {}
        for hexes in GROUPS.values():
            remap.update(tune(hexes, sim, rng))
        modes[mode] = dict(sorted(remap.items()))
    return {
        "notes": "Generated by tools/content/gen_color_vision.py (do not hand-edit). UI colours replaced per colour-blind mode.",
        "minDistance": MIN_DISTANCE,
        "groups": GROUPS,
        "modes": modes,
    }


def main():
    text = json.dumps(build(), indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(REPO)} is out of date. Run: python3 tools/content/gen_color_vision.py")
            sys.exit(1)
        print("color_vision OK")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
