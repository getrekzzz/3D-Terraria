#!/usr/bin/env python3
"""Builds data/reference/*.json (Terraria concept databases used to measure coverage) from the tables in
tools/content/reference/. Names only, no copied prose. Usage: gen_reference.py [--check]"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
OUT = REPO / "data" / "reference"
sys.path.insert(0, str(HERE / "reference"))

import bosses_events  # noqa: E402
import items  # noqa: E402
import world  # noqa: E402


def entry(cid, name, kind, stage="", source="", mechanics=None, note=""):
    e = {"id": f"terraria:{cid}", "name": name, "kind": kind}
    if stage:
        e["stage"] = stage
    if source:
        e["source"] = source
    if mechanics:
        e["mechanics"] = mechanics
    if note:
        e["note"] = note
    return e


def rows(text):
    return [line.split("|") for line in text.strip().splitlines() if line.strip()]


def build():
    dbs = {}
    item_entries = []
    for metal in items.PRE_METALS:
        for key, label, kind in items.PRE_PIECES:
            item_entries.append(entry(f"{metal}_{key}", f"{metal.title()} {label}", kind, "early", "craft" if key != "ore" else "mining"))
    for metal in items.HARD_METALS:
        for key, label, kind in items.HARD_PIECES:
            item_entries.append(entry(f"{metal}_{key}", f"{metal.title()} {label}", kind, "hardmode", "craft" if key != "ore" else "mining"))
    for kind, text in items.NOTABLE.items():
        for cid, name, stage, source in rows(text):
            item_entries.append(entry(cid, name, kind, stage, source))
    dbs["items"] = item_entries
    dbs["enemies"] = [entry(c, n, "enemy", s, src, m.split(",")) for c, n, s, src, m in rows(world.ENEMIES)]
    dbs["bosses"] = [entry(c, n, "boss", s, src, m, note) for c, n, s, src, m, note in bosses_events.BOSSES]
    dbs["events"] = [entry(c, n, "event", s, src, m, note) for c, n, s, src, m, note in bosses_events.EVENTS]
    dbs["npcs"] = [entry(c, n, "town_npc", s, src, m) for c, n, s, src, m in bosses_events.NPCS]
    dbs["progression"] = [entry(c, n, "stage", s, f"after {req}" if req else "", m) for c, n, s, req, m in bosses_events.PROGRESSION]
    dbs["biomes"] = [entry(c, n, kind, source=layer) for c, n, layer, kind in rows(world.BIOMES)]
    dbs["tiles"] = [entry(c, n, kind, s) for c, n, s, kind in rows(world.TILES)]
    dbs["buffs"] = [entry(c, n, kind) for c, n, kind in rows(world.BUFFS)]
    dbs["projectiles"] = [entry(c, n, kind) for c, n, kind in rows(world.PROJECTILES)]
    dbs["recipes"] = [entry(c, n, "recipe", source=st, mechanics=[i.strip() for i in ins.split(",")]) for c, n, st, ins in rows(world.RECIPES)]
    return dbs


def render(category, entries):
    ids = [e["id"] for e in entries]
    dupes = sorted({i for i in ids if ids.count(i) > 1})
    if dupes:
        raise SystemExit(f"{category}: duplicate ids {dupes}")
    doc = {"format": "strata-reference", "version": 1, "category": category,
           "comment": "Terraria concepts for coverage tracking (names only). Generated by tools/content/gen_reference.py.",
           "entries": entries}
    return json.dumps(doc, indent=1) + "\n"


def main():
    dbs = build()
    stale = []
    for category, entries in dbs.items():
        text = render(category, entries)
        path = OUT / f"{category}.json"
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
            continue
        OUT.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    if stale:
        print("stale reference files (run tools/content/gen_reference.py):", ", ".join(stale))
        return 1
    print(f"{sum(len(e) for e in dbs.values())} reference entries in {len(dbs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
