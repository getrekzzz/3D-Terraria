#!/usr/bin/env python3
"""Generates the enemy banners (X-03) from banners.json and the enemy data: one wall banner per enemy that is worth
coins (not bosses or critters), variants grouped under one banner. Each banner is a tile object (also an item) whose
`banner.enemies` lists the creatures it counts and empowers against, plus its model spec for the Dungeon's `banner`
generator (bgen/dungeon_decor.py): cloth in the enemy's tint (or a palette colour), an emblem by its tags.

Outputs (do not hand-edit; `--check` fails when they are out of date):
  data/items/generated/banners.json   tile objects + the Monster Banner buff
  tools/blender/assets.d/x-03-banners.json   model specs
"""
import hashlib
import json
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
TABLE = HERE / "banners.json"
OUT_DATA = REPO / "data" / "items" / "generated" / "banners.json"
OUT_ASSETS = REPO / "tools" / "blender" / "assets.d" / "x-03-banners.json"


def load_jsonc(path: pathlib.Path):
    return json.loads(re.sub(r"^\s*//.*$", "", path.read_text(encoding="utf-8"), flags=re.M))


def enemies() -> dict:
    """Every enemy declared in any content file listed by data/manifest.json."""
    found = {}
    for rel in load_jsonc(REPO / "data" / "manifest.json")["files"]:
        f = REPO / "data" / rel
        if f == OUT_DATA or not f.exists():
            continue
        doc = load_jsonc(f)
        for e in doc.get("enemies", []) if isinstance(doc, dict) else []:
            found[e["id"]] = e
    return found


def eligible(e: dict) -> bool:
    tags = e.get("tags", [])
    return e.get("boss") is None and "critter" not in tags and "boss" not in tags and e.get("value", 0) > 0


def stable(key: str) -> int:
    return int(hashlib.sha1(key.encode()).hexdigest()[:8], 16)


def emblem(table: dict, tags: list) -> str:
    for rule in table["emblems"]:
        if any(t in tags for t in rule["tags"]):
            return rule["shape"]
    return table["defaultEmblem"]


def shade(hex_color: str, k: float) -> str:
    c = [int(hex_color[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{max(0, min(255, int(v * k))):02x}" for v in c)


def build(table: dict, found: dict):
    grouped = {m for members in table["groups"].values() for m in members}
    banners = {g: list(members) for g, members in table["groups"].items()}
    for eid, e in found.items():
        if eid in grouped or eid in table["exclude"] or not eligible(e):
            continue
        banners[eid] = [eid]
    objects, assets = [], {}
    for group in sorted(banners):
        members = [m for m in banners[group] if m in found]
        if not members:
            continue
        lead = found[members[0]]
        name = table["names"].get(group, lead.get("name", group.replace("_", " ").title()))
        oid = f"{group}_banner"
        objects.append({
            "id": oid, "name": f"{name} Banner",
            "description": f"Nearby players deal more damage to and take less from: {name}.",
            "size": [2, 4, 1], "anchor": "wall", "hitPoints": 1, "itemCategory": "furniture", "itemValue": 1000,
            "banner": {"enemies": members}, "tags": ["banner"],
        })
        tint = lead.get("tint")
        cloth = tint if isinstance(tint, str) and tint.startswith("#") and tint.lower() not in ("#ffffff", "#fff") \
            else table["palette"][stable(group) % len(table["palette"])]
        cloth = shade(cloth, 0.8)
        assets[oid] = {"generator": "banner", "params": {
            "cloth": cloth, "trim": "#d8c070", "emblem": "#f0ead8", "shape": emblem(table, lead.get("tags", [])),
            "hem": table["hems"][stable(oid) % len(table["hems"])]}}
    buff = {"id": "monster_banner", "name": "Monster Banner", "color": "#d8c070",
            "description": "Increased damage against and reduced damage from the creatures of nearby banners."}
    data = {"buffs": [buff], "tileObjects": objects}
    spec = {"comment": "X-03 enemy banners (generated by tools/content/gen_banners.py; the Dungeon's banner generator).",
            "objects": assets}
    header = "// Generated by tools/content/gen_banners.py from tools/content/banners.json; do not edit.\n"
    return header + json.dumps(data, indent=1) + "\n", json.dumps(spec, indent=1) + "\n", len(objects)


def main(argv):
    data, assets, n = build(load_jsonc(TABLE), enemies())
    if "--check" in argv:
        ok = OUT_DATA.exists() and OUT_DATA.read_text(encoding="utf-8") == data and OUT_ASSETS.exists() \
            and OUT_ASSETS.read_text(encoding="utf-8") == assets
        print(f"banners: {n} {'up to date' if ok else 'OUT OF DATE (run tools/content/gen_banners.py)'}")
        return 0 if ok else 1
    OUT_DATA.parent.mkdir(parents=True, exist_ok=True)
    OUT_DATA.write_text(data, encoding="utf-8")
    OUT_ASSETS.write_text(assets, encoding="utf-8")
    print(f"banners: wrote {n} banners")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
