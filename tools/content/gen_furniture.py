#!/usr/bin/env python3
"""Generates the furniture families (X-03) from furniture_families.json: for every material, the full set of pieces
as tile objects (each also an item) with recipes, plus their model specs for tools/blender.

Outputs (do not hand-edit; `--check` fails when they are out of date):
  data/items/generated/furniture_families.json  tile objects + recipes
  tools/blender/assets.d/x-03-families.json      model specs (generator furniture_piece)
"""
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
TABLE = HERE / "furniture_families.json"
OUT_DATA = REPO / "data" / "items" / "generated" / "furniture_families.json"
OUT_ASSETS = REPO / "tools" / "blender" / "assets.d" / "x-03-families.json"


def piece_id(family: dict, piece: str) -> str:
    """An existing id, an explicit id (one that would clash with another object), or <family>_<piece>."""
    return family.get("existing", {}).get(piece) or family.get("ids", {}).get(piece) or f"{family['id']}_{piece}"


def build(table: dict):
    objects, recipes, assets = [], [], {}
    for fam in table["families"]:
        existing = fam.get("existing", {})
        for piece, spec in table["pieces"].items():
            if piece in existing:
                continue  # the plain wooden set already exists (data/tileobjects, its models in assets.json)
            oid = piece_id(fam, piece)
            obj = {"id": oid, "name": f"{fam['name']} {spec['name']}", "size": spec["size"]}
            for key in ("anchor", "collision", "interaction", "containerSlots", "housing", "light"):
                if key in spec:
                    obj[key] = spec[key]
            if "providesStations" in spec:
                obj["stations"] = spec["providesStations"]
            if "flame" in spec:
                obj["flame"] = {**spec["flame"], "color": fam.get("flame", "#ff8a2a")}
            obj["hitPoints"] = spec["hitPoints"]
            if fam["material"] in ("granite", "marble", "obsidian", "glass", "lihzahrd_brick"):
                obj["breakTool"] = "pick"
            obj["itemCategory"] = spec.get("category", "light" if "light" in spec else "furniture")
            if "maxStack" in spec:
                obj["itemMaxStack"] = spec["maxStack"]
            obj["itemValue"] = spec["value"]
            obj["tags"] = ["furniture", f"family_{fam['id']}", f"piece_{piece}"]
            objects.append(obj)

            inputs = [{"item": fam["material"], "count": spec["count"]}] + spec.get("extra", [])
            stations = spec["stationsUsed"] if "stationsUsed" in spec else [fam.get("station", spec.get("station", "work_bench"))]
            if "stationsUsed" not in spec and fam.get("station") and spec.get("station") == "anvil":
                stations = ["anvil"]
            recipe = {"id": oid, "output": oid, "inputs": inputs, "stations": stations}
            if spec.get("output", 1) != 1:
                recipe["count"] = spec["output"]
            recipes.append(recipe)

            params = {"piece": piece, "mat": fam["mat"], "tint": fam["tint"], "trim": fam["trim"], "cloth": fam["cloth"]}
            if "trimTint" in fam:
                params["trimTint"] = fam["trimTint"]
            assets[oid] = {"generator": "furniture_piece", "params": params}
    return objects, recipes, assets


def render(objects, recipes, assets):
    lines = ["{",
             '  // Furniture families (X-03), generated by tools/content/gen_furniture.py from furniture_families.json.',
             "  // Do not edit by hand: change the table and run the generator.",
             '  "tileObjects": [']
    lines += ["    " + json.dumps(o, ensure_ascii=False) + ("," if i < len(objects) - 1 else "") for i, o in enumerate(objects)]
    lines += ["  ],", '  "recipes": [']
    lines += ["    " + json.dumps(r, ensure_ascii=False) + ("," if i < len(recipes) - 1 else "") for i, r in enumerate(recipes)]
    lines += ["  ]", "}", ""]
    data = "\n".join(lines)
    spec = {"comment": "X-03 furniture families: generated by tools/content/gen_furniture.py (do not edit by hand).",
            "objects": assets}
    asset_text = "{\n" + f' "comment": {json.dumps(spec["comment"])},\n "objects": {{\n' + ",\n".join(
        f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in assets.items()) + "\n }\n}\n"
    return data, asset_text


def main(argv):
    table = json.loads(TABLE.read_text(encoding="utf-8"))
    data, assets = render(*build(table))
    if "--check" in argv:
        stale = [p for p, text in ((OUT_DATA, data), (OUT_ASSETS, assets)) if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"ERROR: {p.relative_to(REPO)} is out of date; run tools/content/gen_furniture.py")
        if not stale:
            print(f"furniture families up to date ({data.count('piece_')} pieces)")
        return 1 if stale else 0
    OUT_DATA.write_text(data, encoding="utf-8")
    OUT_ASSETS.write_text(assets, encoding="utf-8")
    print(f"wrote {OUT_DATA.relative_to(REPO)} and {OUT_ASSETS.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
